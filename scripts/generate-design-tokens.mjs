function ensureDir(path) {
  mkdirSync(dirname(path), { recursive: true });
}

function tsObject(object, indent = 2) {
  return JSON.stringify(object, null, indent)
    .replace(/"([^"]+)":/g, '$1:')
    .replace(/"/g, "'");
}

function cssVars(object, prefix) {
  return Object.entries(object)
    .map(([key, value]) => `  --${prefix}-${kebab(key)}: ${value};`)
    .join('\n');
}

function kebab(value) {
  return value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/_/g, '-').toLowerCase();
}

function dartColor(hex) {
  return `Color(0xFF${hex.replace('#', '').toUpperCase()})`;
}

function dartMap(object) {
  return Object.entries(object)
    .map(([key, value]) => `    '${key}': ${dartColor(value)},`)
    .join('\n');
}

function write(path, content) {
  ensureDir(path);
  writeFileSync(path, content);
  console.log(`generated ${path.replace(`${repoRoot}/`, '')}`);
}

